    "<!-- markdownlint-disable MD013 MD034 MD052 MD060 -->",
    "<!-- This page is generated by scripts/build-pipeline-settings-doc.mjs: change the script or the JSON schema, not the page -->",
    "",
    "# Pipeline Settings",
    "",
    "Pipeline Settings is the editor of the sfdx-hardis configuration of a project: where the branches deploy, how deployments run, which tickets are linked, what a contributor is offered. This page lists every setting of the panel, tab by tab, with the key it writes in `.sfdx-hardis.yml`.",
    "",
    "## Open it",
    "",
    "- In the [DevOps Pipeline](vscode-extension-devops-pipeline.md) panel, open the gear menu and click **Pipeline Settings**.",
    "- The panel opens read-only. Click **Edit**, change what you need, then **Save**.",
    "- A setting left empty reads **Not defined**, or shows its default value followed by **Default**.",
    "- **Docs** next to a setting opens its documentation page.",
    "",
    "## Two scopes",

#!/usr/bin/env node
/**
 * Writes the Pipeline Settings reference page of the VS Code guides, and the
 * numbered pills of its screenshots.
 *
 *   node scripts/build-pipeline-settings-doc.mjs
 *   node scripts/build-pipeline-settings-doc.mjs --reference <path to pipeline-settings-reference.json>
 *
 * The page lists every setting of the Pipeline Settings panel, tab by tab and
 * scope by scope. Nothing in it is written by hand except the introduction
 * below, so a setting added to the panel gets its row the next time this runs:
 *
 *   1. In ../vscode-sfdx-hardis: yarn screenshots pipeline-settings-reference
 *      captures every tab and writes doc-screenshots/pipeline-settings-reference.json,
 *      the rows of each capture and where each one sits.
 *   2. In ../vscode-sfdx-hardis: python scripts/build-doc-images.py --settings-reference-only
 *      copies the captures to docs/assets/images/vscode-guide/.
 *   3. Here: this script writes docs/vscode-extension-pipeline-settings.md and the
 *      pills of those images in docs/assets/annotations.json. The key, the
 *      description, the default and the documentation link of a setting come from
 *      config/sfdx-hardis.jsonschema.json.
 *   4. Here: node scripts/annotate-doc-images.mjs draws the pills, and
 *      node scripts/check-doc-pills.mjs proves the page and the images agree.
 */
import fs from "fs";
import path from "path";
import { fileURLToPath } from "url";
import { SPEC } from "./annotate-doc-images.mjs";

const HERE = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(HERE, "..");
const PAGE = path.join(ROOT, "docs", "vscode-extension-pipeline-settings.md");
const SCHEMA = path.join(ROOT, "config", "sfdx-hardis.jsonschema.json");
const GUIDE_FOLDER = "vscode-guide";
const IMAGE_PREFIX = "pipeline-settings-ref-";
const DOC_URL_ROOT = "https://sfdx-hardis.cloudity.com/";

const referenceArg = process.argv.indexOf("--reference");
const REFERENCE =
  referenceArg > -1
    ? path.resolve(process.argv[referenceArg + 1])
    : path.resolve(ROOT, "..", "vscode-sfdx-hardis", "doc-screenshots", "pipeline-settings-reference.json");

// Sub-fields of the anonymization editor: one config key, several rows in the panel
const ANONYMIZATION_ROWS = {
  "Enforce in local runs": ["enforceLocally"],
  "Report files": ["channels", "files"],
  "API endpoint": ["channels", "api"],
  Email: ["channels", "email"],
  Messaging: ["channels", "messaging"],
};

// How far left of a setting label its pill sits, in pixels of the capture
const PILL_OFFSET_PX = 30;
// The pill is drawn up and left of its point (it is made to sit on the corner of a box): this
// brings its centre back on the line of the label
const PILL_DROP_PX = 7;

main();

function main() {
  if (!fs.existsSync(REFERENCE)) {
    console.error(`${REFERENCE} not found. Run "yarn screenshots pipeline-settings-reference" in vscode-sfdx-hardis first.`);
    process.exit(1);
  }
  const reference = JSON.parse(fs.readFileSync(REFERENCE, "utf8"));
  const schema = JSON.parse(fs.readFileSync(SCHEMA, "utf8")).properties;

  const pills = {};
  const lines = introduction();
  for (const scope of ["global", "branch"]) {
    lines.push(...scopeIntroduction(scope));
    for (const tab of reference.tabs.filter((one) => one.scope === scope)) {
      lines.push(...tabSection(tab, schema, reference, pills));
    }
  }
  lines.push(...closing());
  fs.writeFileSync(PAGE, lines.join("\n") + "\n", "utf8");
  console.log(`written ${path.relative(ROOT, PAGE)}`);

  writePills(pills);
}

